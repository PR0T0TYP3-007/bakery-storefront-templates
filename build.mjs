/**
 * Assembles the deployable site into ./dist.
 *
 *   node build.mjs                               the listing page + every template
 *   node build.mjs --base /repo-name/            same, for a project Pages sub-path
 *   node build.mjs --template 01-editorial-atelier   one template, at the root
 *
 * The templates themselves stay buildless: nothing here bundles, minifies or
 * transpiles. It copies files, rewrites a couple of path prefixes, and injects
 * a robots meta that GitHub Pages cannot send as a header.
 */

import { readFile, writeFile, mkdir, rm, cp, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

// fileURLToPath, not url.pathname: the latter keeps percent-encoding and the
// leading slash on Windows drive letters, so a path containing a space
// silently resolves to nothing.
const ROOT = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(ROOT, 'dist');
const TEMPLATES_DIR = path.join(ROOT, 'templates');

const argv = process.argv.slice(2);
const flag = (name) => {
  const i = argv.indexOf(`--${name}`);
  return i > -1 ? argv[i + 1] : null;
};

const ONLY = flag('template');
/** Where the site is rooted once deployed. A project Pages site is /<repo>/. */
const BASE = (flag('base') ?? '/').replace(/\/*$/, '/');

const ALL_TEMPLATES = (await readdir(TEMPLATES_DIR, { withFileTypes: true }))
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

if (ONLY && !ALL_TEMPLATES.includes(ONLY)) {
  console.error(`No such template: ${ONLY}\nAvailable: ${ALL_TEMPLATES.join(', ')}`);
  process.exit(1);
}

const TEMPLATES = ONLY ? [ONLY] : ALL_TEMPLATES;

/* Files inside a template that exist for development only. */
const TEMPLATE_JUNK = ['package.json', 'tests', 'README.md', 'node_modules'];

const TEXT = new Set(['.html', '.js', '.css', '.json', '.svg', '.webmanifest']);
const ROBOTS = '<meta name="robots" content="noindex, nofollow">';

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else out.push(full);
  }
  return out;
}

/**
 * @param {string} dir
 * @param {[RegExp, string][]} rules
 */
async function rewriteIn(dir, rules) {
  let touched = 0;
  for (const file of await walk(dir)) {
    const ext = path.extname(file);
    if (!TEXT.has(ext)) continue;

    const before = await readFile(file, 'utf8');
    let after = before;
    for (const [find, replace] of rules) after = after.replace(find, replace);

    // GitHub Pages cannot send response headers, so noindex has to live in
    // the markup to survive on every host.
    if (ext === '.html' && !after.includes('name="robots"')) {
      after = after.replace('<meta charset="utf-8">', `<meta charset="utf-8">\n${ROBOTS}`);
    }

    if (after !== before) {
      await writeFile(file, after, 'utf8');
      touched++;
    }
  }
  return touched;
}

async function copyTemplate(name, dest) {
  await cp(path.join(TEMPLATES_DIR, name), dest, { recursive: true });
  for (const junk of TEMPLATE_JUNK) {
    await rm(path.join(dest, junk), { recursive: true, force: true });
  }
}

/** Only the photographs the built output actually references. */
async function copyReferencedImages(scanDir, destDir) {
  const referenced = new Set();
  for (const file of await walk(scanDir)) {
    if (!TEXT.has(path.extname(file))) continue;
    const text = await readFile(file, 'utf8');
    for (const m of text.matchAll(/photo-[0-9a-zA-Z_-]+?(?=-(?:sm|md|lg)\.jpg|["'`)\s])/g)) {
      referenced.add(m[0]);
    }
  }

  const src = path.join(ROOT, 'shared', 'img');
  await mkdir(destDir, { recursive: true });

  let copied = 0;
  let skipped = 0;
  for (const name of await readdir(src)) {
    if (referenced.has(name.replace(/-(sm|md|lg)\.jpg$/, ''))) {
      await cp(path.join(src, name), path.join(destDir, name));
      copied++;
    } else skipped++;
  }
  return { copied, skipped };
}

const HEADERS = `# Generated by build.mjs — edit the generator, not this file.
# Cloudflare and Netlify honour this. GitHub Pages cannot send custom headers
# at all, which is why noindex is also injected into the markup.

/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: SAMEORIGIN
  Permissions-Policy: camera=(), microphone=(), geolocation=(), interest-cohort=()
  X-Robots-Tag: noindex, nofollow

# Filenames carry no content hash, so these must revalidate rather than be
# cached hard — otherwise an edit is invisible until the cache expires.
/*.html
  Cache-Control: public, max-age=0, must-revalidate
/
  Cache-Control: public, max-age=0, must-revalidate
/*.css
  Cache-Control: public, max-age=0, must-revalidate
/*.js
  Cache-Control: public, max-age=0, must-revalidate
/*.json
  Cache-Control: public, max-age=0, must-revalidate

# Stable filenames, safe to cache for a year.
/shared/img/*
  Cache-Control: public, max-age=31536000, immutable
/assets/previews/*
  Cache-Control: public, max-age=31536000, immutable
`;

/* ========================================================================= */

console.log(ONLY ? `Building ${ONLY} alone -> dist/` : `Building the full listing -> dist/`);
if (BASE !== '/') console.log(`  base      ${BASE}`);

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });

let notFoundLinks;

if (ONLY) {
  /* --- one template, flattened to the root ------------------------------ */
  await copyTemplate(ONLY, OUT);
  if (existsSync(path.join(ROOT, 'shared', 'js'))) {
    await cp(path.join(ROOT, 'shared', 'js'), path.join(OUT, 'shared', 'js'), { recursive: true });
  }
  const imgs = await copyReferencedImages(OUT, path.join(OUT, 'shared', 'img'));

  const touched = await rewriteIn(OUT, [
    // The template sits two levels deep in the repo and at the root in dist.
    [/\.\.\/\.\.\/shared\//g, 'shared/'],
    // There is no listing page in a single-template build.
    [/\s*<p class="meta"><a href="\.\.\/\.\.\/index\.html">All templates<\/a>[^<]*<\/p>/g, ''],
    [/<a href="\.\.\/\.\.\/index\.html">All templates<\/a>\s*·\s*/g, ''],
  ]);

  notFoundLinks = `<a class="btn" href="${BASE}">Back to the catalogue</a>`;
  console.log(`  images    ${imgs.copied} copied, ${imgs.skipped} skipped as unreferenced`);
  console.log(`  rewrites  ${touched} files`);
} else {
  /* --- the listing page plus every template ----------------------------- */
  await cp(path.join(ROOT, 'index.html'), path.join(OUT, 'index.html'));
  await cp(path.join(ROOT, 'assets', 'previews'), path.join(OUT, 'assets', 'previews'), {
    recursive: true,
  });

  for (const name of TEMPLATES) {
    await copyTemplate(name, path.join(OUT, 'templates', name));
  }

  await cp(path.join(ROOT, 'shared', 'js'), path.join(OUT, 'shared', 'js'), { recursive: true });
  const imgs = await copyReferencedImages(OUT, path.join(OUT, 'shared', 'img'));

  // No path rewriting: the repo layout is preserved, so ../../shared/ is
  // still correct. Only the robots meta is injected.
  const touched = await rewriteIn(OUT, []);

  notFoundLinks =
    `<a class="btn" href="${BASE}">All templates</a>` +
    TEMPLATES.map(
      (t) =>
        `\n      <a class="btn btn--quiet" href="${BASE}templates/${t}/">${t.replace(/^\d+-/, '').replace(/-/g, ' ')}</a>`
    ).join('');

  console.log(`  templates ${TEMPLATES.join(', ')}`);
  console.log(`  images    ${imgs.copied} copied, ${imgs.skipped} skipped as unreferenced`);
  console.log(`  rewrites  ${touched} files`);
}

/* --- shared output ------------------------------------------------------ */

await writeFile(path.join(OUT, '_headers'), HEADERS, 'utf8');

// Stop GitHub Pages running Jekyll, which silently drops any path starting
// with an underscore — js/pages/_page.js among them.
await writeFile(path.join(OUT, '.nojekyll'), '', 'utf8');

// The 404 links are absolute on purpose: this page is served for any missing
// path at any depth, so a relative link would resolve against whatever the
// visitor mistyped. BASE is what makes that correct under a sub-path.
